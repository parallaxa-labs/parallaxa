#!/usr/bin/env python3
"""Regenerate data/locale/{en-US,ja-JP,id-ID}.ini from the UX contract.

Source of truth: docs/ux/stage-plugin-ux.md section 8 ("Locale keys"), a
Markdown table | `Key` | English | Japanese | Indonesian |. The .ini files hold
exactly those keys and must include Stage.Description (used by obs_module_description).

Usage (from the repo root or anywhere):
    py -3.10 tools/gen-locale.py           # write the three files
    py -3.10 tools/gen-locale.py --check   # exit 1 if they are stale

It also lists keys that sections 1 to 7 of the spec reference but section 8
does not define (a spec gap for the UX owner; those keys are not invented
here). Standard library only.

Copyright (C) 2026 Parallaxa Labs
SPDX-License-Identifier: GPL-2.0-or-later
"""
import argparse
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
PLUGIN = HERE.parent
REPO = PLUGIN
SPEC = REPO / "docs" / "ux" / "stage-plugin-ux.md"
OUT = PLUGIN / "data" / "locale"

# Keys the plugin code needs even if a future spec revision drops them
# (Stage.Description feeds obs_module_description). Used only when section 8
# does not define the key itself.
REQUIRED = {
    "Stage.Description": (
        "Depth, parallax, virtual camera moves and visual effects for 2D VTubers.",
        "2D VTuber向けの奥行き・パララックス・バーチャルカメラワーク・映像エフェクト。",
        "Kedalaman, paralaks, gerakan kamera virtual, dan efek visual untuk VTuber 2D.",
    ),
}

LOCALES = (("en-US", "English"), ("ja-JP", "Japanese"), ("id-ID", "Indonesian"))

ROW = re.compile(r"^\|\s*`(Stage\.[A-Za-z0-9_.]+)`\s*\|(.*)\|\s*$")
KEY_REF = re.compile(r"`(Stage\.[A-Za-z0-9_.]+)`")


def parse_spec(text):
    """Returns (ordered list of (key, en, ja, id), set of keys used in 1..7)."""
    sec8 = re.search(r"^## 8\..*?$(.*?)^## 9\.", text, re.S | re.M)
    if not sec8:
        sys.exit(f"{SPEC}: section 8 not found")
    before = text[: sec8.start()]
    rows, seen = [], set()
    for line in sec8.group(1).splitlines():
        m = ROW.match(line)
        if not m:
            continue
        cells = [c.strip() for c in m.group(2).split("|")]
        if len(cells) != 3:
            sys.exit(f"bad row (expected 3 text cells): {line}")
        key = m.group(1)
        if key in seen:
            sys.exit(f"duplicate key in section 8: {key}")
        seen.add(key)
        rows.append((key, *cells))
    return rows, set(KEY_REF.findall(before))


def ini_escape(value):
    # OBS text-lookup ends a quoted value at the first unescaped quote and
    # converts \" \n \t \r back; nothing else is special inside quotes. It has
    # no escape for a backslash itself, so refuse one rather than mangle it.
    if "\\" in value:
        sys.exit(f"backslash not supported in locale value: {value}")
    return value.replace('"', '\\"')


def render(idx, lang, rows, extra):
    out = [
        f"# Parallaxa - {lang}.",
        "# GENERATED by tools/gen-locale.py from docs/ux/stage-plugin-ux.md",
        "# section 8. Edit the spec table, then rerun the script; do not edit here.",
        "# Filter display names stay in English in every language.",
        "",
    ]
    if extra:
        for key, vals in extra.items():
            out.append(f'{key}="{ini_escape(vals[idx])}"')
        out.append("")
    prefix = None
    for row in rows:
        key = row[0]
        group = key.split(".")[1]
        if prefix is not None and group != prefix:
            out.append("")
        prefix = group
        out.append(f'{key}="{ini_escape(row[1 + idx])}"')
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if files are stale")
    args = ap.parse_args()

    rows, referenced = parse_spec(SPEC.read_text(encoding="utf-8"))
    defined = {r[0] for r in rows}
    extra = {k: v for k, v in REQUIRED.items() if k not in defined}
    stale = []
    for idx, (loc, lang) in enumerate(LOCALES):
        path = OUT / f"{loc}.ini"
        text = render(idx, lang, rows, extra)
        old = path.read_bytes().decode("utf-8") if path.exists() else None
        if old == text:
            continue
        if args.check:
            stale.append(path.name)
        else:
            path.write_bytes(text.encode("utf-8"))  # LF, no BOM
            print(f"wrote {path} ({len(rows) + len(extra)} keys)")

    # Keys a section 1-7 table names that section 8 lacks. Placeholders such
    # as `Stage.Hotkey.Move` are fine; anything listed here needs a spec row.
    missing = sorted(k for k in referenced - defined - set(extra) if not k.endswith("."))
    if missing:
        print("spec gap: referenced in sections 1-7 but not in section 8:")
        for k in missing:
            print(f"  {k}")
    if stale:
        print("stale: " + ", ".join(stale) + " (run tools/gen-locale.py)")
        return 1
    print(f"{len(rows)} spec keys + {len(extra)} extra, in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
