// Generates standalone-dict.gen.ts: the strings of the standalone Stage dock
// (Parallaxa data/dock/dock-standalone.html) in EN, JA and ID, inlined because a
// file:// page cannot fetch them. Only the keys the standalone components use
// are kept (found in their sources: literal `stage.`, `stage_sa.`, `recipe.` and
// `ui.` keys, and `stage.x.${...}` template prefixes), stored once as a key list plus one value list per language, which
// keeps the page under its 32 KB gzipped JS cap. Missing JA / ID strings fall back to
// English, as in the i18n build plugin (scripts/vite-plugins.ts).
//
//   node src/dock/gen-dict.ts          rewrite src/dock/standalone-dict.gen.ts
// logic.test.ts fails when the committed file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FX_SLIDERS } from './fx.ts';

const here = dirname(fileURLToPath(import.meta.url));
const LANGS = ['en', 'ja', 'id'] as const;
/** Sources of the standalone dock that call t(). */
export const SOURCES = [
  'StageControl.svelte',
  'ViewPad.svelte',
  'Manual.svelte',
  'Layers.svelte',
  'Effects.svelte',
  'Looks.svelte',
  'Range.svelte',
  'Standalone.svelte',
  'model.svelte.ts',
];
export const OUT = join(here, 'standalone-dict.gen.ts');
/** Keys the standalone sources name but never show there: host states only other hosts report (StageControl banner). */
export const STUDIO_ONLY = ['stage.obs_auth', 'stage.obs_down'];
/** Template prefixes whose run-time ids are known: only those keys are kept (no fx_param.lut / leak: picked by select or in OBS). */
export const PREFIX_IDS: Record<string, readonly string[]> = { 'stage.fx_param.': FX_SLIDERS.map((s) => s.p) };
const SEP = '|';

type Dict = Record<string, string>;

function dicts(): Record<(typeof LANGS)[number], Dict> {
  const read = (p: string): Dict => JSON.parse(readFileSync(p, 'utf8')) as Dict;
  const out = {} as Record<(typeof LANGS)[number], Dict>;
  for (const l of LANGS) out[l] = { ...read(join(here, '../lib/i18n', `${l}.json`)), ...read(join(here, 'i18n', `${l}.json`)) };
  return out;
}

/** Keys used by the standalone sources: [exact keys, template prefixes]. */
export function usedKeys(): [Set<string>, Set<string>] {
  const exact = new Set<string>();
  const prefix = new Set<string>();
  for (const f of SOURCES) {
    const src = readFileSync(join(here, f), 'utf8');
    for (const m of src.matchAll(/['"`]((?:stage|stage_sa|recipe|ui)\.[a-z0-9_.]*)(\$\{)?/g)) {
      const k = m[1] as string;
      if (m[2]) prefix.add(k);
      else if (!k.endsWith('.') && !/\.(css|ts|svelte)$/.test(k)) exact.add(k); // not './stage.css'
    }
  }
  return [exact, prefix];
}

/** The generated module source. */
export function generate(): string {
  const d = dicts();
  const [exact, prefix] = usedKeys();
  const keys = Object.keys(d.en)
    .filter((k) => (exact.has(k) || [...prefix].some((p) => k.startsWith(p) && (PREFIX_IDS[p]?.includes(k.slice(p.length)) ?? true))) && !STUDIO_ONLY.includes(k))
    .sort();
  const missing = [...exact].filter((k) => !(k in d.en) && !STUDIO_ONLY.includes(k));
  if (missing.length) throw new Error(`gen-dict: keys used but not defined: ${missing.join(', ')}`);
  const list = (l: (typeof LANGS)[number]) =>
    keys.map((k) => {
      const v = d[l][k] ?? (d.en[k] as string);
      if (v.includes(SEP)) throw new Error(`gen-dict: ${l} ${k} contains "${SEP}"`);
      return v;
    });
  const lit = (a: string[]) => JSON.stringify(a.join(SEP));
  return [
    '// Generated by `node src/dock/gen-dict.ts` from src/lib/i18n/*.json and src/dock/i18n/*.json. Do not edit.',
    '// The standalone dock strings: one key list, one value list per language, "|"-separated.',
    '// Copyright (C) 2026 Parallaxa Labs',
    '// SPDX-License-Identifier: GPL-2.0-or-later',
    `export const KEYS = ${lit(keys)};`,
    `export const EN = ${lit(list('en'))};`,
    `export const JA = ${lit(list('ja'))};`,
    `export const ID = ${lit(list('id'))};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, generate());
  console.log(`gen-dict: wrote ${OUT}`);
}
